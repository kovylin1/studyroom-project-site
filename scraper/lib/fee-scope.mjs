// fee-scope.mjs — что именно за число дал источник: цену программы или цену кампуса.
//
// ЗАЧЕМ. QS не публикует цен программ вовсе. В его выгрузке у каждой ценовой строки
// стоит `feeBasis: 'campusLevelStated'`, а `feeNote` говорит прямым текстом:
// «стоимость обучения кампуса для выбранного уровня (Campus Costs), а не цена
// конкретной программы; портал программных цен не показывает». Одно число садится
// на весь уровень: у Manchester Met портал показывает вилку «Max £25 926 /
// Min £14 883», а в выгрузку идёт 16 236 и ложится на все 37 бакалаврских программ.
//
// ЧТО ЭТО ЛОМАЛО. Правило владельца «когда у программы несколько цен, берём
// минимальную» задумано для сравнимых чисел. Кампусная сумма сравнима с ценой
// программы не больше, чем средняя температура по больнице с температурой больного,
// и по минимуму она регулярно выигрывала: на 25.08 такое было у 1 729 программ
// в 105 вузах. Hertfordshire MSc Data Science показывал 13 401 при цене edvoy
// 22 450 по этой же программе.
//
// ПРАВИЛО. Цена программы важнее цены кампуса, независимо от суммы. Кампусная
// ставится, только когда программной нет вовсе. Приоритета между агрегаторами это
// не вводит: сравниваются по-прежнему все источники, но сперва внутри своего вида.
// Кампусная сумма не пропадает — она остаётся в `tuitionVariants` со своим
// источником, так что на странице её видно.

export const CAMPUS_LEVEL_BASIS = 'campusLevelStated';

// Строка выгрузки -> 'campus' | 'program'
export function feeScope(row) {
  return (row && (row.feeBasis || row.tuitionBasis)) === CAMPUS_LEVEL_BASIS ? 'campus' : 'program';
}

// Кандидаты одной программы -> только программные, если они есть.
// Пустой список и список без программных цен возвращаются как есть.
export function preferProgramScope(list) {
  if (!Array.isArray(list) || list.length === 0) return list || [];
  const program = list.filter((c) => c.scope !== 'campus');
  return program.length ? program : list;
}
