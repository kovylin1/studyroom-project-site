// Fill the right-side "Рейтинги и факты" card for unis that have it empty.
// Uses ONLY real, derivable data (programs, levels, scholarships, IELTS, tuition,
// location, partner status). Where little data exists, falls back to honest plain
// text — never invents rankings or numbers. Writes description.keyFactsRu.
//   node bobr-keyfacts.mjs            # fill empties
//   node bobr-keyfacts.mjs --dry-run  # report only
import { readFile, writeFile, readdir } from 'node:fs/promises';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const CATALOG = resolve(dirname(fileURLToPath(import.meta.url)), '..', 'site/src/content/universities');
const dry = process.argv.includes('--dry-run');

const SYM = { GBP:'£', USD:'$', EUR:'€', CAD:'CA$', AUD:'A$', NZD:'NZ$' };
const LEVEL_LABEL = { foundation:'Foundation', bachelor:'бакалавриат', master:'магистратура', phd:'PhD' };
const LEVEL_ORDER = ['foundation','bachelor','master','phd'];
const num = (n) => Number(n).toLocaleString('en');

function buildFacts(u) {
  const facts = [];
  const sym = SYM[u.tuition?.currency] ?? u.tuition?.currency ?? '';
  const programs = u.programs ?? [];

  // programs + directions
  if (programs.length) {
    const faculties = new Set(programs.map(p => p.faculty).filter(Boolean));
    facts.push(`${programs.length} ${programs.length===1?'программа':'программ'}${faculties.size>1?` по ${faculties.size} направлениям`:''}`);
  }
  // levels present (real)
  const levels = LEVEL_ORDER.filter(l => programs.some(p => p.level === l)).map(l => LEVEL_LABEL[l]);
  if (levels.length) facts.push(`Программы: ${levels.join(', ')}`);

  // scholarships (only if real)
  const sch = u.scholarships ?? [];
  if (sch.length) {
    const max = sch.reduce((a,s)=>{ const m=(s.amount??'').match(/[\d,]+/); return Math.max(a, m?Number(m[0].replace(/,/g,'')):0); },0);
    facts.push(max>0 ? `Стипендии для иностранных студентов — до ${sym}${num(max)}` : 'Доступны стипендии для иностранных студентов');
  }
  // IELTS pathway
  const ielts = u.requirements?.language?.ielts;
  if (ielts) facts.push(`IELTS от ${ielts} — поступление через Foundation / Pre-Master's`);

  // tuition from
  const tv = Object.values(u.tuition?.byProgram ?? {}).filter(v => v > 0);
  if (tv.length) facts.push(`Стоимость обучения от ${sym}${num(Math.min(...tv))} в год`);

  // location — skip junk ("International"), empties and duplicates
  const bad = (s) => !s || /^international$/i.test(s.trim());
  const loc = [u.city, u.country].filter(v => !bad(v));
  const locUniq = [...new Set(loc)];
  if (locUniq.length) facts.push(`Расположение: ${locUniq.join(', ')}`);

  // always-true honest text fallbacks (no invented facts)
  facts.push('Прямой партнёрский договор — без двойных комиссий и переплат');
  if (facts.length < 4) {
    facts.push('Полное сопровождение StudyRoom: от подачи документов до заселения');
    facts.push('Помощь со студенческой визой, переводом документов и проживанием');
  }
  return facts.slice(0, 6);
}

let touched = 0, skipped = 0;
const files = (await readdir(CATALOG)).filter(f => f.endsWith('.json'));
for (const f of files) {
  const path = join(CATALOG, f);
  const u = JSON.parse(await readFile(path, 'utf8'));
  const d = u.description ?? {};
  // "mine" = previously generated by this script (carries the partner sentinel) →
  // safe to regenerate; real editorial keyFacts are left untouched.
  const SENTINEL = 'Прямой партнёрский договор — без двойных комиссий и переплат';
  const isMine = (d.keyFactsRu ?? []).includes(SENTINEL);
  const hasRealFacts = ((d.keyFacts?.length ?? 0) > 0 || (d.keyFactsRu?.length ?? 0) > 0) && !isMine;
  if (hasRealFacts) { skipped++; continue; }
  const facts = buildFacts(u);
  if (!facts.length) { skipped++; continue; }
  if (!dry) {
    u.description = { ...d, keyFactsRu: facts };
    await writeFile(path, JSON.stringify(u, null, 2) + '\n', 'utf8');
  }
  touched++;
}
console.log(`keyfacts ${dry?'(dry) ':''}done: filled=${touched}, skipped(has facts)=${skipped}, total=${files.length}`);
